import { describe, expect, it } from "vitest";
import { readImageDimensions } from "@/lib/images/dimensions";

describe("readImageDimensions", () => {
  it("reads PNG dimensions", () => {
    const bytes = new Uint8Array([
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
      0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
      0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x03, 0x00
    ]);

    expect(readImageDimensions(bytes.buffer)).toEqual({ width: 1024, height: 768 });
  });

  it("reads GIF dimensions", () => {
    const bytes = new Uint8Array([
      0x47, 0x49, 0x46, 0x38, 0x39, 0x61,
      0x40, 0x01, 0xf0, 0x00
    ]);

    expect(readImageDimensions(bytes.buffer)).toEqual({ width: 320, height: 240 });
  });

  it("reads JPEG dimensions from SOF0", () => {
    const bytes = new Uint8Array([
      0xff, 0xd8,
      0xff, 0xe0, 0x00, 0x04, 0x00, 0x00,
      0xff, 0xc0, 0x00, 0x11, 0x08, 0x02, 0x58, 0x03, 0x20,
      0x03, 0x01, 0x11, 0x00, 0x02, 0x11, 0x00, 0x03, 0x11, 0x00
    ]);

    expect(readImageDimensions(bytes.buffer)).toEqual({ width: 800, height: 600 });
  });

  it("reads WebP VP8X dimensions", () => {
    const bytes = new Uint8Array([
      0x52, 0x49, 0x46, 0x46, 0x1e, 0x00, 0x00, 0x00,
      0x57, 0x45, 0x42, 0x50,
      0x56, 0x50, 0x38, 0x58, 0x0a, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00,
      0x7f, 0x02, 0x00,
      0xdf, 0x01, 0x00
    ]);

    expect(readImageDimensions(bytes.buffer)).toEqual({ width: 640, height: 480 });
  });

  it("returns null for unknown formats", () => {
    expect(readImageDimensions(new Uint8Array([1, 2, 3, 4]).buffer)).toBeNull();
  });
});
